fn main() {
    let num:u8=10;// unsigned number- 0 to 2^(n-1)
    let inum:i8=-20;// signed number- -(2^n-1) to 2^n-1
    println!("The unsigned number is: {}", num);
    println!("The signed number is: {}", inum);
    println!("Hello, world!");

    
}

// Unsigned number= 0 to 2^(n-1)
// Signed number= -(2^n-1) to 2^n-1
//8,16,32,64,128 bits
//n= number of bits

